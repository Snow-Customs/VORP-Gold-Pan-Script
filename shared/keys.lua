function ResolveKey(key)
    if type(key) == "number" then
        return key
    end
    if type(key) == "string" then
        local name = key:upper():gsub("^INPUT_", "")
        local hash = KeyMap[name]
        if hash then
            return hash
        end
        print(("[snow_goldpan] Unbekannte Taste in Config: %s"):format(key))
    end
    return nil
end
